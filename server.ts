app.all('/api/test-formspree', async (req, res) => {
  const formId = process.env.FORMSPREE_FORM_ID;
  if (!formId || formId.trim() === '') {
    return res.status(400).json({ 
      status: "failed", 
      error: "FORMSPREE_FORM_ID is missing in environment variables" 
    });
  }

  console.log(`[Formspree Test] Initiating validation for Formspree ID: ${formId}`);

  try {
    const response = await fetch(`https://formspree.io/f/${formId}`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json'
      },
      body: JSON.stringify({
        email: "test-khc@example.com",
        message: "System Integration Test Run"
      })
    });

    let responseData: any = {};
    try {
      responseData = await response.json();
    } catch (e) {
      responseData = { text: await response.text().catch(() => 'No readable response body') };
    }

    if (response.ok) {
      return res.json({
        status: "success",
        message: "Formspree is connected and working perfectly!",
        formId: formId,
        formspreeResponse: responseData
      });
    } else {
      return res.status(response.status).json({
        status: "failed",
        error: "Formspree returned a non-success status code",
        statusCode: response.status,
        formspreeResponse: responseData
      });
    }
  } catch (error: any) {
    console.error('[Formspree Test] Secure Connection Failure:', error);
    return res.status(500).json({
      status: "failed",
      error: "Failed to establish a network connection to Formspree endpoint",
      details: error.message
    });
  }
});

