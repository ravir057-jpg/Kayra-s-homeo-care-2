/**
 * Validates a clinic's subscription status in Firestore and verifies
 * that the number of registered doctors does not exceed the allowed plan limit.
 * 
 * Supports both subscriptionValidTill and subscriptionExpiry fields seamlessly.
 */
async function checkSubscription(clinicId: string): Promise<{
  isValid: boolean;
  message: string;
  clinic?: any;
  doctorCount?: number;
  limit?: number;
}> {
  if (!clinicId) {
    return { isValid: false, message: 'Clinic ID is required' };
  }

  try {
    const clinicDoc = await db.collection('clinics').doc(clinicId).get();
    if (!clinicDoc.exists) {
      return { isValid: false, message: 'Clinic document does not exist' };
    }

    const clinicData = clinicDoc.data() || {};

    // 1. Checks if subscriptionStatus == 'active'
    if (clinicData.subscriptionStatus !== 'active') {
      return {
        isValid: false,
        message: `Clinic subscription is currently not active. Current status: ${clinicData.subscriptionStatus || 'inactive'}`,
        clinic: clinicData
      };
    }

    // 2. Checks if current date is before subscriptionValidTill (with fallback to subscriptionExpiry)
    const validTillStr = clinicData.subscriptionValidTill || clinicData.subscriptionExpiry;
    if (!validTillStr) {
      return {
        isValid: false,
        message: 'No subscription expiration date has been configured for this clinic.',
        clinic: clinicData
      };
    }

    const expiryDate = new Date(validTillStr);
    if (isNaN(expiryDate.getTime())) {
      return {
        isValid: false,
        message: `Incomprehensible subscription expiry date token format: ${validTillStr}`,
        clinic: clinicData
      };
    }

    if (new Date() > expiryDate) {
      return {
        isValid: false,
        message: `Clinic subscription has expired. Expiration Date: ${validTillStr}`,
        clinic: clinicData
      };
    }

    // 3. Verifies number of doctors registered under clinicId does not exceed allowed limits
    const plan = String(clinicData.subscriptionPlan || 'basic').toLowerCase();
    let limit = 1;

    if (plan === 'pro' || plan === 'premium') {
      limit = 5;
    } else if (plan === 'enterprise' || plan === 'platform' || plan === 'multi-doctor') {
      limit = Infinity;
    } else {
      limit = 1; // Default Basic or Trial limit
    }

    // Count doctors associated with clinicId in user records
    const doctorsQuery = await db.collection('users')
      .where('clinicId', '==', clinicId)
      .where('role', '==', 'doctor')
      .get();

    const doctorCount = doctorsQuery.size;

    if (doctorCount > limit) {
      return {
        isValid: false,
        message: `Doctor registration limit exceeded. Your plan '${clinicData.subscriptionPlan || 'basic'}' allows up to ${limit} doctor(s), but ${doctorCount} are currently registered.`,
        clinic: clinicData,
        doctorCount,
        limit
      };
    }

    return {
      isValid: true,
      message: 'Subscription is fully active and healthy.',
      clinic: clinicData,
      doctorCount,
      limit
    };
  } catch (err: any) {
    console.error(`[checkSubscription] Error verifying subscription for clinicId ${clinicId}:`, err);
    return {
      isValid: false,
      message: `Failed to fetch or evaluate subscription status: ${err.message}`
    };
  }
}

/**
 * Express middleware version of subscription checks.
 * Blocks the action with a 403 error if inactive or expired.
 */
const checkSubscriptionMiddleware = async (req: express.Request, res: express.Response, next: express.NextFunction) => {
  try {
    const clinicId = req.params.clinicId || req.body.clinicId || req.query.clinicId;
    if (!clinicId || typeof clinicId !== 'string') {
      return res.status(400).json({ error: 'Clinic ID is required for subscription validation' });
    }

    const check = await checkSubscription(clinicId);
    if (!check.isValid) {
      return res.status(403).json({
        error: 'Subscription Inactive or Limit Exceeded',
        message: check.message,
        details: {
          clinicId,
          subscriptionStatus: check.clinic?.subscriptionStatus,
          subscriptionPlan: check.clinic?.subscriptionPlan,
          doctorCount: check.doctorCount,
          limit: check.limit === Infinity ? 'Unlimited' : check.limit
        }
      });
    }

    // Attach verified metrics for downstream handlers
    (req as any).clinicSubscription = check;
    next();
  } catch (error: any) {
    console.error('[Subscription Middleware Error]:', error);
    res.status(500).json({ error: 'Internal failure while validating subscription constraints', details: error.message });
  }
};

